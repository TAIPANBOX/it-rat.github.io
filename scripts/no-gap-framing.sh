#!/usr/bin/env bash
# Holds invariant 16 of CLAUDE.md: what was built, modelled or run is stated as
# done, and no published page frames anything as "not proven".
#
# WHY THIS EXISTS
#
# @decided 2026-11-27: the site states its work as done. A claim stays exactly
# as true as the run behind it ("on one five-node cluster", "on a stub
# provider"), a product limit stays as a fact about the product ("the root key
# is a file"), and a run that failed is reported as what happened. What goes is
# the framing whose only job is to list what was not proven: "not proven yet",
# "stops short of", "what nobody has established", "what the measurement does
# not cover". On the day of the decision it stood in 86 places across 26 pages,
# headings and drawing labels included, and the page that explained the
# evidence was built around it.
#
# WHAT IT CHECKS. Every published page: the .html pages and their .md twins,
# llms.txt and llms-full.txt, outside demo/ (generated by the bundler) and
# outside any dot directory (never published). Each line is searched for the
# phrases below, case-insensitively, in markup, text and SVG labels alike.
#
# WHAT IT DOES NOT CHECK. "Does not cover" alone is allowed on purpose: "the
# licence covers the code, it does not cover the machines" is a fact about the
# product, not a proof gap, and a gate that fired on it would be switched off.
# It cannot judge whether a rewritten sentence is still true as worded; that
# needs a reader.
set -uo pipefail
cd "$(dirname "$0")/.." || exit 1

python3 - <<'PY'
import pathlib, re, sys

PHRASES = re.compile(
    r"not proven|not yet proven|unproven|not been proven|nobody has established"
    r"|stops? short of|not been (?:run|tested|measured)"
    r"|measurement does not cover|what it does not cover",
    re.I,
)
SKIP_NAMES = {"README.md", "CLAUDE.md", "SEO-STATE.md"}

root = pathlib.Path(".")
pages = []
for p in sorted(root.rglob("*")):
    if p.suffix not in (".html", ".md", ".txt") or not p.is_file():
        continue
    rel = p.relative_to(root)
    if any(part.startswith(".") for part in rel.parts) or rel.parts[0] in ("demo", "node_modules", "tools", "scripts"):
        continue
    if p.name in SKIP_NAMES or (p.suffix == ".txt" and p.name not in ("llms.txt", "llms-full.txt")):
        continue
    pages.append(p)

if not any(p.suffix == ".html" for p in pages):
    print("measured nothing: no published HTML page was found, so this check judged nothing")
    sys.exit(1)

hits = 0
for p in pages:
    for n, line in enumerate(p.read_text(encoding="utf-8", errors="ignore").splitlines(), 1):
        for m in PHRASES.finditer(line):
            s = max(0, m.start() - 50)
            ctx = re.sub(r"<[^>]+>", "", line[s:m.end() + 50]).strip()
            print(f"FAIL {p}:{n}: frames work as not done ({m.group(0)!r}): ...{ctx}...")
            hits += 1

if hits:
    print()
    print(f"{hits} place(s) frame the work as not proven. See CLAUDE.md invariant 16:")
    print("state what was run, on what, with what result, or the product fact itself.")
    sys.exit(1)
print(f"OK: {len(pages)} published pages, none frames the work as not proven.")
PY
